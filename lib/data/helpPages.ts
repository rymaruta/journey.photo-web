/**
 * **使い方の頁（/help）の台帳**（2026-11-12・札 journey.photo-ios#517・owner「使い方を優先的に作りたいな」）。
 *
 * 設計は資料「説明なしで分かるアプリ」の「使い方の頁の並び」:
 *   - 1頁は絵1枚と3行。1行目は何ができるか、2行目はどこから始めるか、3行目は気をつけること
 *   - 「うまくいかないとき」「送るもの、送らないもの」は、要る頁だけ畳んで下に置く（`folds`）
 *   - 題は検索で探す言葉のまま（「すれちがい乗車券の使い方」）
 *
 * 🔴 **中身は今の本番の iPhone のアプリ（`CHECKED_APP_VERSION`）のコードを読んで書いた。推定で書かない。**
 * 画面の名前は画面の字と同じに書く（ボタンの字は「」でくくる）。数字は実装の値と同じ:
 *   乗車券のひとこと 20字      iOS `PassExchange.noteLimit`
 *   旅のあいだ 50km            iOS `PassExchange.travelThresholdKm`
 *   知らせ 15分に1回まで       iOS `PassExchange.noticeInterval`
 *   夕方 18時                  iOS `PassPrivacyText.eveningDetail`
 *   リクエストの間 文字3通まで  `api-user/src/dm.ts` の `DM_REQUEST_MAX`
 *   通報で運営に届く 20通まで   `api-user/src/dm.ts` の `DM_REPORT_LAST`
 *   硬貨 1日3件・99枚まで・24時間で取り消し・かけら5つ  `api-user/src/trunk.ts` の冒頭の決まり
 * 数字は `lib/data/__tests__/helpPages.test.ts` が実装の値と突き合わせる。
 *
 * 言葉の決まり（2026-11-12 owner）: 公式の場所は「観光スポット」、画面の文を「・」「·」で区切らない、
 * 「撮りどき」「捨てる」などの禁止語を使わない（同じ試験が見る）。
 *
 * **作らない頁**: 第3弾（旅行プランと共有、行った県マップ、バッジ、とおまわり号）は直す予定の画面なので作らない。
 * プロフィールの QR は今の本番のアプリ（1.1.83）に無い（1.1.84 で入る）ので、入ってから書く。
 */

export type HelpFold = {
    /** 畳んだ見出し（押すと開く） */
    title: string;
    items: string[];
    /** 畳んだ中に置くリンク（サイトの中の頁だけ） */
    links?: Array<{ href: string; label: string }>;
};

export type HelpPage = {
    slug: string;
    /** h1 と頁の title（サイト名はルートの `title.template` が足す）。検索で探す言葉のまま */
    title: string;
    /** 目次の札の短い名前 */
    cardTitle: string;
    /** 目次の札の1行 */
    summary: string;
    /** 検索結果に出る説明文（meta description） */
    description: string;
    /** 使える所（題の上に出す） */
    scope: string;
    /** 絵の読み上げの説明（絵は `app/help/HelpFigure.tsx`） */
    figureLabel: string;
    /** 3行 */
    lines: [string, string, string];
    folds?: HelpFold[];
};

